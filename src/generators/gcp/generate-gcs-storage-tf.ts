/**
 * Generate storage.tf with GCS buckets for object storage
 *
 * Creates:
 * - GCS buckets with for_each over configured bucket names
 * - Access logs of their objects (Data Access audit logs, other buckets
 *   excluded)
 * - Uniform bucket-level access (no ACLs)
 * - CORS configuration (allow all origins — presigned URLs control access)
 * - Soft delete policy with 7-day retention
 * - IAM: roles/storage.objectUser for all service accounts
 * - IAM: roles/iam.serviceAccountTokenCreator for presigned URL signing,
 *   granted on each runtime service account itself (a project-level grant
 *   would let every service act as every service account in the project)
 * - The IAM Service Account Credentials API (signBlob), kept on destroy
 *
 * force_destroy = true allows Terraform to delete non-empty buckets.
 * WARNING: This is permanent — NOT recoverable.
 */

import type { GCPInfraConfig } from '../../types/config.ts';
import { buildGcsStorageBucketName } from '../../utils/gcp/build-gcs-storage-bucket-name.ts';

export function generateGcsStorageTf(config: GCPInfraConfig): string {
  if (config.storageBuckets.length === 0) {
    return '';
  }

  const bucketNames = config.storageBuckets.map((b) => ({
    key: b,
    name: buildGcsStorageBucketName({
      projectName: config.projectName,
      bucket: b,
      environment: config.environment,
      gcpProjectId: config.gcpProjectId,
      naming: config.naming,
    }),
  }));
  const bucketMap = bucketNames
    .map(({ key, name }) => `    "${key}" = "${name}"`)
    .join('\n');
  // Access logs of every other bucket in the project are dropped
  const keptBuckets = bucketNames
    .map(({ name }) => `resource.labels.bucket_name=\\"${name}\\"`)
    .join(' OR ');

  return `# GCS Object Storage Buckets
# Generated by: npx tsdevstack infra:generate

locals {
  storage_buckets = {
${bucketMap}
  }
}

# =============================================================================
# GCS Buckets
# =============================================================================

resource "google_storage_bucket" "storage" {
  for_each = local.storage_buckets

  name          = each.value
  location      = var.gcp_region
  project       = var.gcp_project_id
  force_destroy = true

  uniform_bucket_level_access = true
  # Nobody can make the bucket or a file public; signed URLs still work
  public_access_prevention    = "enforced"

  cors {
    origin          = ["*"]
    method          = ["GET", "PUT", "POST", "DELETE", "HEAD"]
    response_header = ["ETag", "Content-Length", "Content-Type"]
    max_age_seconds = 3600
  }

  soft_delete_policy {
    retention_duration_seconds = 604800  # 7 days
  }
}

# =============================================================================
# IAM — grant storage.objectUser to all runtime service accounts
# =============================================================================

resource "google_storage_bucket_iam_member" "storage_object_user" {
  for_each = {
    for pair in setproduct(keys(local.storage_buckets), local.services) :
    "\${pair[0]}-\${pair[1]}" => {
      bucket  = pair[0]
      service = pair[1]
    }
  }

  bucket = google_storage_bucket.storage[each.value.bucket].name
  role   = "roles/storage.objectUser"
  member = "serviceAccount:\${google_service_account.runtime[each.value.service].email}"
}

# =============================================================================
# IAM — let each runtime service account sign blobs as itself
# Presigned URLs from Application Default Credentials call signBlob on the
# service's own account. Granted on that account only: a project-level grant
# would let every service act as every service account in the project.
# =============================================================================

resource "google_service_account_iam_member" "storage_token_creator" {
  for_each = toset(local.services)

  service_account_id = google_service_account.runtime[each.key].name
  role               = "roles/iam.serviceAccountTokenCreator"
  member             = "serviceAccount:\${google_service_account.runtime[each.key].email}"
}

# signBlob is served by the IAM Service Account Credentials API. Left enabled
# when buckets are removed: CI (Workload Identity Federation) uses it too.
resource "google_project_service" "iamcredentials" {
  project            = var.gcp_project_id
  service            = "iamcredentials.googleapis.com"
  disable_on_destroy = false
}

# =============================================================================
# Access logs: every read and write of the storage buckets' objects
# Cloud Storage's Data Access audit logs, in Cloud Logging (infra:logs
# bucket-{name}). Google turns them on per project, not per bucket, so an
# exclusion drops the other buckets' entries (the Terraform state, the SPA
# buckets): excluded entries are not stored or charged. This setting is
# authoritative for Cloud Storage: one made by hand in the console is
# replaced.
# =============================================================================

resource "google_project_iam_audit_config" "storage" {
  project = var.gcp_project_id
  service = "storage.googleapis.com"

  audit_log_config {
    log_type = "DATA_READ"
  }

  audit_log_config {
    log_type = "DATA_WRITE"
  }
}

resource "google_logging_project_exclusion" "storage_access_other_buckets" {
  name        = "storage-access-other-buckets"
  project     = var.gcp_project_id
  description = "Cloud Storage access logs of buckets other than the storage buckets"
  filter      = "logName=\\"projects/\${var.gcp_project_id}/logs/cloudaudit.googleapis.com%2Fdata_access\\" AND resource.type=\\"gcs_bucket\\" AND NOT (${keptBuckets})"
}

# =============================================================================
# Output
# =============================================================================

output "storage_buckets" {
  description = "Storage bucket names and metadata"
  value = {
    for key, bucket in google_storage_bucket.storage :
    key => {
      name     = bucket.name
      location = bucket.location
      url      = bucket.url
    }
  }
}
`;
}
