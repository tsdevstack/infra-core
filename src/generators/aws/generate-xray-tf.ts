/**
 * Generate xray.tf: X-Ray Transaction Search, which the X-Ray OTLP endpoint
 * needs before it accepts spans
 *
 * Transaction Search is an account setting: spans are stored in the
 * aws/spans log group (CloudWatch Logs pricing, 1% indexed for search
 * free). Removing it from Terraform leaves the setting on (the provider's
 * documented behavior), so a destroy keeps it.
 */

import { AWS_TRANSACTION_SEARCH_LOG_GROUPS } from '../../constants/index.ts';

export function generateXrayTf(): string {
  const logGroupArns = AWS_TRANSACTION_SEARCH_LOG_GROUPS.map(
    (group) =>
      `        "arn:aws:logs:\${var.aws_region}:\${var.aws_account_id}:log-group:${group}:*",`,
  ).join('\n');

  return `# X-Ray Transaction Search
# Generated by: npx tsdevstack infra:generate
#
# The X-Ray OTLP endpoint (traces from services, workers, Next.js and Kong's
# collector) only accepts spans once Transaction Search is on. It is an
# account setting, kept when the environment is destroyed.

# X-Ray writes the spans to CloudWatch Logs
resource "aws_cloudwatch_log_resource_policy" "xray_transaction_search" {
  policy_name = "\${var.project_name}-transaction-search"

  policy_document = jsonencode({
    Version = "2012-10-17"
    Statement = [{
      Sid       = "TransactionSearchXRayAccess"
      Effect    = "Allow"
      Principal = { Service = "xray.amazonaws.com" }
      Action    = "logs:PutLogEvents"
      Resource = [
${logGroupArns}
      ]
      Condition = {
        ArnLike      = { "aws:SourceArn" = "arn:aws:xray:\${var.aws_region}:\${var.aws_account_id}:*" }
        StringEquals = { "aws:SourceAccount" = var.aws_account_id }
      }
    }]
  })
}

resource "aws_xray_trace_segment_destination" "main" {
  destination = "CloudWatchLogs"

  depends_on = [aws_cloudwatch_log_resource_policy.xray_transaction_search]
}
`;
}
