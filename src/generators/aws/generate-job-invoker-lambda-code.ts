/**
 * Generate Job Invoker Lambda code
 *
 * Creates a Node.js Lambda function that:
 * 1. Retrieves job auth secret from Secrets Manager
 * 2. Calls the target service endpoint via CloudMap DNS
 *
 * Services always run at least one task on AWS, so no wake-up step is needed.
 *
 * This Lambda runs in VPC to resolve CloudMap DNS names.
 * EventBridge Scheduler triggers it with { serviceName, path, jobName, method,
 * timeoutSeconds }: the job's HTTP method and how long to wait (httpTimeout).
 * The function's own timeout is a few seconds longer than the longest job's,
 * so a run that times out still logs its end.
 * Every line it writes starts with job=<name>, so each job's runs can be
 * read on their own (infra:logs).
 */

import {
  DEFAULT_SCHEDULED_JOB_METHOD,
  SCHEDULED_JOB_HTTP_TIMEOUT,
} from '../../constants/index.ts';

export function generateJobInvokerLambdaCode(): string {
  return `// Job Invoker Lambda for scheduled jobs
// Generated by: npx tsdevstack infra:generate

const { SecretsManagerClient, GetSecretValueCommand } = require('@aws-sdk/client-secrets-manager');

const secrets = new SecretsManagerClient({});

const NAMESPACE = process.env.CLOUDMAP_NAMESPACE;
const JOB_SECRET_ARN = process.env.JOB_SECRET_ARN;

exports.handler = async (event) => {
  // Defaults for events from schedules made before method and timeoutSeconds
  const {
    serviceName,
    path,
    jobName,
    method = '${DEFAULT_SCHEDULED_JOB_METHOD}',
    timeoutSeconds = ${SCHEDULED_JOB_HTTP_TIMEOUT.aws.default},
  } = event;

  // Every line starts with job=<name>: infra:logs reads a job's runs by it
  const job = jobName || \`\${serviceName}\${path}\`;
  const log = (message) => console.log(\`job=\${job} \${message}\`);
  const logError = (message) => console.error(\`job=\${job} \${message}\`);

  if (!serviceName || !path) {
    logError('Run failed: the event has no serviceName or path');
    return {
      statusCode: 400,
      body: JSON.stringify({ error: 'Missing serviceName or path' }),
    };
  }

  const started = Date.now();
  try {
    // Get job auth secret
    const { SecretString } = await secrets.send(
      new GetSecretValueCommand({ SecretId: JOB_SECRET_ARN })
    );

    if (!SecretString) {
      throw new Error('Failed to retrieve job auth secret');
    }

    // Build URL using CloudMap DNS
    const url = \`http://\${serviceName}.\${NAMESPACE}:8080\${path}\`;
    log(\`Run started: \${method} \${url}\`);

    // Make HTTP request to service
    const response = await fetch(url, {
      method,
      headers: {
        'Content-Type': 'application/json',
        'X-Job-Secret': SecretString,
      },
      // The function runs a few seconds longer, so a hung job still logs its end
      signal: AbortSignal.timeout(timeoutSeconds * 1000),
    });

    const responseText = await response.text();

    if (!response.ok) {
      logError(
        \`Run finished: \${response.status} (\${responseText.substring(0, 1000)})\`
      );
      // Already logged; the throw makes EventBridge retry
      const failure = new Error(\`Job failed with status \${response.status}\`);
      failure.logged = true;
      throw failure;
    }

    log(\`Run finished: \${response.status} in \${Date.now() - started}ms\`);
    return {
      statusCode: response.status,
      body: responseText,
    };
  } catch (error) {
    if (!error?.logged) {
      logError(\`Run failed: \${error instanceof Error ? error.message : String(error)}\`);
    }
    throw error; // Rethrow to trigger retry policy
  }
};
`;
}
