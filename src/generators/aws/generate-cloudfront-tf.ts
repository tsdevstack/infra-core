/**
 * Generate cloudfront.tf with CloudFront distribution for API
 *
 * CloudFront provides CDN for the API with WAF protection at edge.
 * WAF is CLOUDFRONT scope in us-east-1, attached to all CloudFront distributions.
 *
 * Also defines the edge client address function: a CloudFront function on the
 * viewer request that sets EDGE_CLIENT_IP_HEADER to the viewer's address
 * (`event.viewer.ip`, AWS: "the IP address of the viewer (client) that sent
 * the request"), replacing any value the client sent. Kong reads that header
 * as the client address; the Next.js distributions use the same function so
 * the frontend can name its visitor to Kong.
 */

import { EDGE_CLIENT_IP_HEADER } from '../../constants/index.ts';

export function generateCloudfrontTf(): string {
  // CloudFront Functions: header names must be lowercase in function code
  const edgeHeader = EDGE_CLIENT_IP_HEADER.toLowerCase();

  return `# CloudFront Distribution (API)
# Generated by: npx tsdevstack infra:generate
#
# CDN with WAF protection at edge (CLOUDFRONT scope, us-east-1).

# =============================================================================
# Edge client address function
# =============================================================================
# Runs on every viewer request of the API and Next.js distributions and sets
# ${EDGE_CLIENT_IP_HEADER} to the viewer's address (event.viewer.ip), replacing
# a client-sent value. Kong reads it as the client address for its per-client
# limits (KONG_REAL_IP_HEADER); the Next.js servers read it as the visitor
# they name to Kong (TSDEVSTACK_CLIENT_IP_HEADER). X-Forwarded-For cannot be
# used: CloudFront appends the viewer and the ALB appends CloudFront's edge.

resource "aws_cloudfront_function" "edge_client_ip" {
  name    = "\${var.project_name}-\${var.environment}-edge-client-ip"
  runtime = "cloudfront-js-2.0"
  comment = "Set ${EDGE_CLIENT_IP_HEADER} to the viewer's address"
  publish = true
  code    = <<-EOF
    function handler(event) {
      event.request.headers['${edgeHeader}'] = { value: event.viewer.ip };
      return event.request;
    }
  EOF
}

# =============================================================================
# CloudFront Distribution
# =============================================================================

resource "aws_cloudfront_distribution" "main" {
  enabled         = true
  is_ipv6_enabled = true
  web_acl_id      = aws_wafv2_web_acl.main.arn
  # API domain derived from base_domain (e.g., api.example.com)
  # Wildcard cert covers *.example.com including api.example.com
  aliases         = var.base_domain != "" ? [local.api_domain] : []
  price_class     = "PriceClass_100"
  http_version    = "http2and3"

  # Origin: ALB (Kong handles all routing and failover)
  origin {
    domain_name = aws_lb.main.dns_name
    origin_id   = "alb"

    custom_origin_config {
      http_port              = 80
      https_port             = 443
      origin_protocol_policy = "https-only"
      origin_ssl_protocols   = ["TLSv1.2"]
    }

    # Origin verification header - ALB validates this to prevent direct access
    # Requests without this header get 403 at ALB level
    custom_header {
      name  = "X-Origin-Verify"
      value = random_password.origin_verify_secret.result
    }
  }

  default_cache_behavior {
    target_origin_id       = "alb"
    viewer_protocol_policy = "redirect-to-https"
    allowed_methods        = ["GET", "HEAD", "OPTIONS", "PUT", "POST", "PATCH", "DELETE"]
    cached_methods         = ["GET", "HEAD"]

    # No caching for API - all requests go to origin
    cache_policy_id            = "4135ea2d-6df8-44a3-9df3-4b5a84be39ad"  # CachingDisabled
    # AllViewer: every viewer header reaches the origin, the edge client
    # address header included
    origin_request_policy_id   = "216adef6-5c7f-47e4-b989-5492eafa07d3"  # AllViewer
    response_headers_policy_id = aws_cloudfront_response_headers_policy.security_headers.id

    function_association {
      event_type   = "viewer-request"
      function_arn = aws_cloudfront_function.edge_client_ip.arn
    }
  }

  # Use ACM cert if base_domain is set, otherwise CloudFront default cert
  dynamic "viewer_certificate" {
    for_each = var.base_domain != "" ? [1] : []
    content {
      acm_certificate_arn      = local.cloudfront_certificate_arn
      ssl_support_method       = "sni-only"
      minimum_protocol_version = "TLSv1.2_2021"
    }
  }

  dynamic "viewer_certificate" {
    for_each = var.base_domain == "" ? [1] : []
    content {
      cloudfront_default_certificate = true
    }
  }

  logging_config {
    bucket          = aws_s3_bucket.cloudfront_logs.bucket_domain_name
    prefix          = "api/"
    include_cookies = false
  }

  restrictions {
    geo_restriction {
      restriction_type = "none"
    }
  }

  tags = { Name = "\${var.project_name}-cloudfront" }
}
`;
}
