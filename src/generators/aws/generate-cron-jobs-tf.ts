/**
 * Generate cron-jobs.tf: each cron job's ECS task definition, log group and
 * EventBridge schedule
 *
 * A cron job runs its service's image as `dumb-init node dist/cron.js
 * <name>`, one Fargate task per run, with the service's task role in the
 * private subnets, as the service's workers do. Its schedule starts the task
 * with RunTask directly (no Lambda in the path), as the cron scheduler role.
 *
 * The task definition here is the first revision. Deploys register a new one
 * with the image they deployed, DATABASE_URL, and the job's current name and
 * timeout, and point the schedule at it: the schedule ignores that change.
 * A schedule gets no retries: a failed start waits for the next time.
 * Everything is for_each over var.cron_jobs; the scheduler role exists only
 * while there is a cron job, so environments without one get nothing.
 */

import {
  AWS_CRON_JOB_LOG_STREAM_PREFIX,
  AWS_CRON_JOB_NAME_TAG,
  AWS_CRON_JOB_SERVICE_TAG,
  CRON_JOB_COMMAND,
  CRON_JOB_NAME_ENV,
  CRON_JOB_NAME_PREFIX,
  CRON_JOB_TIMEOUT_ENV,
} from '../../constants/index.ts';

export function generateCronJobsTf(): string {
  const command = ['dumb-init', ...CRON_JOB_COMMAND]
    .map((part) => `"${part}"`)
    .join(', ');
  const tags = (suffix: string): string => `tags = {
    Name                      = "\${var.project_name}-${CRON_JOB_NAME_PREFIX}\${each.key}${suffix}"
    "${AWS_CRON_JOB_SERVICE_TAG}" = each.value.service
    "${AWS_CRON_JOB_NAME_TAG}"     = each.key
  }`;

  return `# Cron Jobs (ECS tasks that EventBridge Scheduler starts)
# Generated by: npx tsdevstack infra:generate

# =============================================================================
# CloudWatch Log Groups
# =============================================================================

resource "aws_cloudwatch_log_group" "cron_job" {
  for_each          = var.cron_jobs
  name              = "/ecs/\${var.project_name}/${CRON_JOB_NAME_PREFIX}\${each.key}"
  retention_in_days = 30
  kms_key_id        = aws_kms_key.logs.arn

  ${tags('-logs')}
}

# =============================================================================
# Task Definitions (the first revision; deploys register the next ones)
# =============================================================================

resource "aws_ecs_task_definition" "cron_job" {
  for_each = var.cron_jobs

  family                   = "\${var.project_name}-${CRON_JOB_NAME_PREFIX}\${each.key}"
  requires_compatibilities = ["FARGATE"]
  network_mode             = "awsvpc"
  cpu                      = each.value.cpu
  memory                   = each.value.memory
  execution_role_arn       = aws_iam_role.ecs_execution.arn
  task_role_arn            = aws_iam_role.task[each.value.service].arn

  container_definitions = jsonencode([{
    name  = "${CRON_JOB_NAME_PREFIX}\${each.key}"
    image = "\${aws_ecr_repository.service[each.value.service].repository_url}:latest"

    # The service's image, its cron job entrypoint
    command = [${command}, each.key]

    environment = [
      { name = "NODE_ENV", value = "production" },
      { name = "SERVICE_NAME", value = each.value.service },
      { name = "${CRON_JOB_NAME_ENV}", value = each.key },
      { name = "${CRON_JOB_TIMEOUT_ENV}", value = tostring(each.value.timeout) },
      { name = "LOG_LEVEL", value = each.value.logLevel },
      { name = "CLOUD_PROVIDER", value = "aws" },
      { name = "SECRETS_PROVIDER", value = "aws" },
      { name = "AWS_REGION", value = var.aws_region },
      { name = "PROJECT_NAME", value = var.project_name },
      { name = "DB_POOL_MAX", value = tostring(each.value.dbPoolMax) },
      { name = "TRACE_SAMPLE_RATE", value = tostring(var.trace_sample_rate) },
      { name = "OTEL_RESOURCE_ATTRIBUTES", value = "aws.log.group.names=\${aws_cloudwatch_log_group.cron_job[each.key].name}" },
    ]

    logConfiguration = {
      logDriver = "awslogs"
      options = {
        "awslogs-group"         = aws_cloudwatch_log_group.cron_job[each.key].name
        "awslogs-region"        = var.aws_region
        "awslogs-stream-prefix" = "${AWS_CRON_JOB_LOG_STREAM_PREFIX}"
      }
    }
  }])

  ${tags('-task')}
}

# =============================================================================
# EventBridge Scheduler Role (starts the cron jobs' tasks)
# =============================================================================

resource "aws_iam_role" "cron_scheduler" {
  count = length(var.cron_jobs) > 0 ? 1 : 0
  name  = "\${var.project_name}-cron-scheduler"

  assume_role_policy = jsonencode({
    Version = "2012-10-17"
    Statement = [{
      Action    = "sts:AssumeRole"
      Effect    = "Allow"
      Principal = { Service = "scheduler.amazonaws.com" }
      Condition = { StringEquals = { "aws:SourceAccount" = var.aws_account_id } }
    }]
  })

  tags = { Name = "\${var.project_name}-cron-scheduler" }
}

resource "aws_iam_role_policy" "cron_scheduler" {
  count = length(var.cron_jobs) > 0 ? 1 : 0
  name  = "run-cron-tasks"
  role  = aws_iam_role.cron_scheduler[0].id

  policy = jsonencode({
    Version = "2012-10-17"
    Statement = [
      {
        # Every revision of the cron jobs' task definitions, in this cluster
        Effect    = "Allow"
        Action    = "ecs:RunTask"
        Resource  = [for name in keys(var.cron_jobs) : "arn:aws:ecs:\${var.aws_region}:\${var.aws_account_id}:task-definition/\${var.project_name}-${CRON_JOB_NAME_PREFIX}\${name}:*"]
        Condition = { ArnEquals = { "ecs:cluster" = aws_ecs_cluster.main.arn } }
      },
      {
        # The roles the tasks run with: the shared execution role, the services' task roles
        Effect    = "Allow"
        Action    = "iam:PassRole"
        Resource  = concat([aws_iam_role.ecs_execution.arn], distinct([for job in values(var.cron_jobs) : aws_iam_role.task[job.service].arn]))
        Condition = { StringLike = { "iam:PassedToService" = "ecs-tasks.amazonaws.com" } }
      }
    ]
  })
}

# =============================================================================
# EventBridge Schedules (per cron job)
# =============================================================================

resource "aws_scheduler_schedule" "cron_job" {
  for_each = var.cron_jobs

  # Named as a trigger's schedule is: {project}-{service}-{name}
  name       = "\${var.project_name}-\${each.value.service}-\${each.key}"
  group_name = "default"

  schedule_expression          = each.value.schedule
  schedule_expression_timezone = each.value.timezone

  flexible_time_window {
    mode = "OFF"
  }

  target {
    arn      = aws_ecs_cluster.main.arn
    role_arn = aws_iam_role.cron_scheduler[0].arn

    ecs_parameters {
      task_definition_arn = aws_ecs_task_definition.cron_job[each.key].arn
      launch_type         = "FARGATE"
      task_count          = 1

      network_configuration {
        subnets          = aws_subnet.private[*].id
        security_groups  = [aws_security_group.ecs.id]
        assign_public_ip = false
      }
    }

    # No retries: a failed start waits for the next scheduled time
    retry_policy {
      maximum_retry_attempts       = 0
      maximum_event_age_in_seconds = 60
    }
  }

  lifecycle {
    # Deploys point the schedule at the task definition revision they register
    ignore_changes = [target[0].ecs_parameters[0].task_definition_arn]
  }

  # The role may start the task once its policy exists (a targeted apply of
  # the schedule creates the policy too)
  depends_on = [aws_iam_role_policy.cron_scheduler]
}
`;
}
