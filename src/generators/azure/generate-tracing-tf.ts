/**
 * Generate tracing.tf: where services, workers, Next.js and Kong send spans
 *
 * Azure Monitor takes OTLP directly (Microsoft's "Ingest OTLP data into Azure
 * Monitor"): a data collection endpoint, and a rule whose trace streams flow
 * into the environment's Log Analytics workspace (the OTelSpans table),
 * linked to Application Insights for its trace views. azurerm 5 can't create
 * a rule with OTel streams, so the rule goes through azapi.
 *
 * Every sender signs in with Entra (Application Insights has local auth off:
 * no connection string, nothing to keep secret) and needs the publisher role
 * on the rule: each backend service's own identity (its workers carry it
 * too), and the system-assigned identities of Kong and the Next.js apps.
 */

import type { AzureInfraConfig } from '../../types/config.ts';
import { toTerraformId } from '../../utils/terraform/to-terraform-id.ts';
import {
  AZURE_DATA_COLLECTION_RULE_API_VERSION,
  AZURE_OTEL_TRACE_STREAMS,
  AZURE_OTLP_TRACES_URL_STREAM,
  AZURE_TRACE_PUBLISHER_ROLE,
} from '../../constants/index.ts';

export function generateTracingTf(config: AzureInfraConfig): string {
  const streams = AZURE_OTEL_TRACE_STREAMS.map((s) => `"${s}"`).join(', ');

  const nextjsPublishers = Object.keys(config.frontends)
    .map((name) => {
      const tfId = toTerraformId(name);
      return `
resource "azurerm_role_assignment" "traces_nextjs_${tfId}" {
  scope                            = azapi_resource.traces_rule.id
  role_definition_name             = "${AZURE_TRACE_PUBLISHER_ROLE}"
  principal_id                     = azurerm_linux_web_app.nextjs_${tfId}.identity[0].principal_id
  skip_service_principal_aad_check = true
}`;
    })
    .join('\n');

  return `# Traces: Application Insights and Azure Monitor's OTLP ingestion
# Generated by: npx tsdevstack infra:generate

resource "azurerm_application_insights" "main" {
  name                = "\${var.project_name}-\${var.environment}-appinsights"
  location            = data.azurerm_resource_group.main.location
  resource_group_name = data.azurerm_resource_group.main.name
  workspace_id        = azurerm_log_analytics_workspace.main.id
  application_type    = "other"

  # Entra sign-in only: no connection string to keep secret
  local_authentication_enabled = false

  tags = local.tags
}

resource "azurerm_monitor_data_collection_endpoint" "traces" {
  name                          = "\${var.project_name}-\${var.environment}-traces"
  location                      = data.azurerm_resource_group.main.location
  resource_group_name           = data.azurerm_resource_group.main.name
  public_network_access_enabled = true
  tags                          = local.tags
}

resource "azapi_resource" "traces_rule" {
  type      = "Microsoft.Insights/dataCollectionRules@${AZURE_DATA_COLLECTION_RULE_API_VERSION}"
  name      = "\${var.project_name}-\${var.environment}-traces"
  parent_id = data.azurerm_resource_group.main.id
  location  = data.azurerm_resource_group.main.location
  tags      = local.tags

  body = {
    properties = {
      dataCollectionEndpointId = azurerm_monitor_data_collection_endpoint.traces.id
      references = {
        applicationInsights = [
          { resourceId = azurerm_application_insights.main.id, name = "appinsights" }
        ]
      }
      # Spans sent straight to the endpoint (no agent)
      directDataSources = {
        otelTraces = [{
          name                           = "otel-traces"
          streams                        = [${streams}]
          enrichWithResourceAttributes   = ["*"]
          enrichWithReference            = "appinsights"
          replaceResourceIdWithReference = true
        }]
      }
      # The same source for the monitoring agent, as in Microsoft's template:
      # Azure counts the Application Insights reference as used only here.
      # No agent runs, so nothing arrives through it.
      dataSources = {
        otelTraces = [{
          name                           = "otel-traces-agent"
          streams                        = [${streams}]
          enrichWithResourceAttributes   = ["*"]
          enrichWithReference            = "appinsights"
          replaceResourceIdWithReference = true
        }]
      }
      destinations = {
        logAnalytics = [
          { workspaceResourceId = azurerm_log_analytics_workspace.main.id, name = "workspace" }
        ]
      }
      dataFlows = [
        { streams = [${streams}], destinations = ["workspace"] }
      ]
    }
  }

  response_export_values = ["properties.immutableId"]
}

locals {
  # OTEL_EXPORTER_OTLP_TRACES_ENDPOINT of every app (the deploy sets it)
  otlp_traces_url = "\${azurerm_monitor_data_collection_endpoint.traces.logs_ingestion_endpoint}/datacollectionRules/\${azapi_resource.traces_rule.output.properties.immutableId}/streams/${AZURE_OTLP_TRACES_URL_STREAM}/otlp/v1/traces"
}

# =============================================================================
# Who may send spans: the publisher role on the rule
# =============================================================================

resource "azurerm_role_assignment" "traces_services" {
  for_each = var.service_key_vaults

  scope                            = azapi_resource.traces_rule.id
  role_definition_name             = "${AZURE_TRACE_PUBLISHER_ROLE}"
  principal_id                     = azurerm_user_assigned_identity.service_secrets[each.key].principal_id
  skip_service_principal_aad_check = true
}

resource "azurerm_role_assignment" "traces_kong" {
  scope                            = azapi_resource.traces_rule.id
  role_definition_name             = "${AZURE_TRACE_PUBLISHER_ROLE}"
  principal_id                     = azurerm_linux_web_app.kong.identity[0].principal_id
  skip_service_principal_aad_check = true
}
${nextjsPublishers}
`;
}
