/**
 * Generate app-service.tf with App Service Plans, Web Apps, and role assignments
 *
 * Kong gets a dedicated App Service Plan.
 * Next.js apps share one App Service Plan.
 * Both have Access Restrictions (service tag + FDID header) for Front Door.
 *
 * Each plan runs `instances` workers (minInstances, at least 1). With
 * `autoscaleMax` set (Standard and Premium SKUs), app-service-autoscale.tf
 * scales between the two and owns the count, so Terraform ignores it after
 * the plan is created. Session affinity is off on every web app: Kong and
 * Next.js are stateless, and the sticky cookie would pin a client to one
 * instance. With more than one instance, App Service's health check takes a
 * failing instance out of rotation (it never removes the last one).
 *
 * With Next.js apps, Kong also gets a private endpoint (see
 * AZURE_KONG_PRIVATE_ENDPOINT): the Next.js servers call Kong through it.
 */

import type {
  AzureInfraConfig,
  AppServicePlanScaling,
} from '../../types/config.ts';
import { toTerraformId } from '../../utils/terraform/to-terraform-id.ts';
import {
  AZURE_APP_SERVICE_HEALTH_CHECK,
  AZURE_KONG_CLIENT_IP_SETTINGS,
  AZURE_KONG_PRIVATE_ENDPOINT,
} from '../../constants/azure-app-service.ts';

export function generateAppServiceTf(config: AzureInfraConfig): string {
  const nextjsEntries = Object.entries(config.frontends);

  // Client address for Kong's per-IP limits (the Azure deploy also merges
  // these into existing apps, whose app_settings Terraform ignores)
  const kongClientIpSettings = Object.entries(AZURE_KONG_CLIENT_IP_SETTINGS)
    .map(([key, value]) => `    ${key.padEnd(35)} = "${value}"`)
    .join('\n');

  const nextjsWebApps = nextjsEntries
    .map(([name]) => {
      const tfId = toTerraformId(name);
      return generateNextjsWebApp(tfId, name, config.nextjsScaling);
    })
    .join('\n');

  const nextjsRoleAssignments = nextjsEntries
    .map(([name]) => {
      const tfId = toTerraformId(name);
      return generateRoleAssignments(
        `nextjs_${tfId}`,
        `azurerm_linux_web_app.nextjs_${tfId}`,
      );
    })
    .join('\n');

  const nextjsPlan =
    nextjsEntries.length > 0
      ? `
resource "azurerm_service_plan" "nextjs" {
  name                = "\${var.project_name}-\${var.environment}-nextjs-plan"
  location            = data.azurerm_resource_group.main.location
  resource_group_name = data.azurerm_resource_group.main.name
  os_type             = "Linux"
  sku_name            = var.nextjs_app_service_sku
  worker_count        = ${config.nextjsScaling.instances}
  tags                = local.tags${generatePlanLifecycle(config.nextjsScaling)}
}
`
      : '';

  const kongPrivateEndpoint =
    nextjsEntries.length > 0 ? generateKongPrivateEndpoint() : '';

  return `# App Service (Kong + Next.js)
# Generated by: npx tsdevstack infra:generate
#
# Kong and Next.js run on App Service for Access Restrictions
# (service tag + FDID header filtering).
# Backends remain on Container Apps with internal ingress.
#
# worker_count is minInstances (at least 1). Plans with autoscale
# (app-service-autoscale.tf) scale between that and maxInstances.

# =============================================================================
# App Service Plans
# =============================================================================

resource "azurerm_service_plan" "kong" {
  name                = "\${var.project_name}-\${var.environment}-kong-plan"
  location            = data.azurerm_resource_group.main.location
  resource_group_name = data.azurerm_resource_group.main.name
  os_type             = "Linux"
  sku_name            = var.kong_app_service_sku
  worker_count        = ${config.kongScaling.instances}
  tags                = local.tags${generatePlanLifecycle(config.kongScaling)}
}
${nextjsPlan}
# =============================================================================
# Kong Web App
# =============================================================================

resource "azurerm_linux_web_app" "kong" {
  name                      = "\${var.project_name}-\${var.environment}-kong"
  location                  = data.azurerm_resource_group.main.location
  resource_group_name       = data.azurerm_resource_group.main.name
  service_plan_id           = azurerm_service_plan.kong.id
  virtual_network_subnet_id = azurerm_subnet.app_service_integration.id
  https_only                = true
  client_affinity_enabled   = false
  tags                      = local.tags

  site_config {
    always_on                               = true
    container_registry_use_managed_identity = true
    minimum_tls_version                     = "1.2"
    ftps_state                              = "Disabled"
    http2_enabled                           = true
    ip_restriction_default_action           = "Deny"
    scm_use_main_ip_restriction             = true${generateHealthCheck(config.kongScaling, AZURE_APP_SERVICE_HEALTH_CHECK.kongPath)}

    ip_restriction {
      service_tag = "AzureFrontDoor.Backend"
      action      = "Allow"
      priority    = 100
      name        = "AllowFrontDoor"

      headers {
        x_azure_fdid     = [azurerm_cdn_frontdoor_profile.main.resource_guid]
        x_fd_health_probe = []
        x_forwarded_for   = []
        x_forwarded_host  = []
      }
    }

    application_stack {
      docker_registry_url = "https://\${azurerm_container_registry.main.login_server}"
      docker_image_name   = "kong:latest"
    }
  }

  app_settings = {
    WEBSITES_PORT                       = "8080"
    WEBSITES_CONTAINER_START_TIME_LIMIT = "600"
    KONG_DATABASE                       = "off"
    KONG_DECLARATIVE_CONFIG             = "/kong/declarative/kong.yml"
${kongClientIpSettings}
  }

  identity {
    type = "SystemAssigned"
  }

  lifecycle {
    ignore_changes = [
      app_settings,
      site_config[0].application_stack[0].docker_image_name,
    ]
  }
}
${nextjsWebApps}
${kongPrivateEndpoint}
# =============================================================================
# Role Assignments
# =============================================================================
${generateRoleAssignments('kong', 'azurerm_linux_web_app.kong')}
${nextjsRoleAssignments}`;
}

/**
 * Lifecycle block for a plan whose instance count autoscale manages
 */
function generatePlanLifecycle(scaling: AppServicePlanScaling): string {
  if (scaling.autoscaleMax === null) return '';
  return `

  lifecycle {
    # Autoscale (app-service-autoscale.tf) manages the instance count
    ignore_changes = [worker_count]
  }`;
}

/**
 * Health check settings for a plan that can run more than one instance
 */
function generateHealthCheck(
  scaling: AppServicePlanScaling,
  path: string,
): string {
  if (scaling.instances <= 1 && scaling.autoscaleMax === null) return '';
  return `
    health_check_path                       = "${path}"
    health_check_eviction_time_in_min       = ${AZURE_APP_SERVICE_HEALTH_CHECK.evictionTimeMin}`;
}

/**
 * Generate HCL for a single Next.js web app
 */
function generateNextjsWebApp(
  tfId: string,
  serviceName: string,
  scaling: AppServicePlanScaling,
): string {
  return `
# =============================================================================
# Next.js Web App: ${serviceName}
# =============================================================================

resource "azurerm_linux_web_app" "nextjs_${tfId}" {
  name                      = "\${var.project_name}-\${var.environment}-${serviceName}"
  location                  = data.azurerm_resource_group.main.location
  resource_group_name       = data.azurerm_resource_group.main.name
  service_plan_id           = azurerm_service_plan.nextjs.id
  virtual_network_subnet_id = azurerm_subnet.app_service_integration.id
  https_only                = true
  client_affinity_enabled   = false
  tags                      = local.tags

  site_config {
    always_on                               = true
    container_registry_use_managed_identity = true
    minimum_tls_version                     = "1.2"
    ftps_state                              = "Disabled"
    http2_enabled                           = true
    ip_restriction_default_action           = "Deny"
    scm_use_main_ip_restriction             = true${generateHealthCheck(scaling, AZURE_APP_SERVICE_HEALTH_CHECK.nextjsPath)}

    ip_restriction {
      service_tag = "AzureFrontDoor.Backend"
      action      = "Allow"
      priority    = 100
      name        = "AllowFrontDoor"

      headers {
        x_azure_fdid     = [azurerm_cdn_frontdoor_profile.main.resource_guid]
        x_fd_health_probe = []
        x_forwarded_for   = []
        x_forwarded_host  = []
      }
    }

    application_stack {
      docker_registry_url = "https://\${azurerm_container_registry.main.login_server}"
      docker_image_name   = "${serviceName}:latest"
    }
  }

  app_settings = {
    WEBSITES_PORT                       = "8080"
    WEBSITES_CONTAINER_START_TIME_LIMIT = "300"
  }

  identity {
    type = "SystemAssigned"
  }

  lifecycle {
    ignore_changes = [
      app_settings,
      site_config[0].application_stack[0].docker_image_name,
    ]
  }
}`;
}

/**
 * Kong's private endpoint and its DNS zone, for the Next.js servers' calls
 */
function generateKongPrivateEndpoint(): string {
  return `
# =============================================================================
# Kong Private Endpoint (Next.js server-side calls)
# =============================================================================
# The Next.js servers call Kong at its default host name (KONG_INTERNAL_URL),
# which resolves to this endpoint inside the VNet, so those calls stay off
# Front Door and its WAF (whose per-IP limit would count every visitor as the
# Next.js app's outbound address). Access restrictions don't apply to private
# endpoint traffic; Front Door keeps using Kong's public access as before.

resource "azurerm_private_dns_zone" "app_service" {
  name                = "${AZURE_KONG_PRIVATE_ENDPOINT.dnsZone}"
  resource_group_name = data.azurerm_resource_group.main.name
  tags                = local.tags
}

resource "azurerm_private_dns_zone_virtual_network_link" "app_service" {
  name                  = "app-service-vnet-link"
  resource_group_name   = data.azurerm_resource_group.main.name
  private_dns_zone_name = azurerm_private_dns_zone.app_service.name
  virtual_network_id    = azurerm_virtual_network.main.id
  registration_enabled  = false
  # Names this zone has no record for (other azurewebsites.net apps with
  # private endpoints) resolve publicly instead of failing
  resolution_policy     = "NxDomainRedirect"
  tags                  = local.tags
}

resource "azurerm_private_endpoint" "kong" {
  name                = "\${var.project_name}-\${var.environment}${AZURE_KONG_PRIVATE_ENDPOINT.nameSuffix}"
  location            = data.azurerm_resource_group.main.location
  resource_group_name = data.azurerm_resource_group.main.name
  subnet_id           = azurerm_subnet.private_endpoints.id
  tags                = local.tags

  private_service_connection {
    name                           = "kong-connection"
    private_connection_resource_id = azurerm_linux_web_app.kong.id
    subresource_names              = ["${AZURE_KONG_PRIVATE_ENDPOINT.subresource}"]
    is_manual_connection           = false
  }

  private_dns_zone_group {
    name                 = "kong-dns"
    private_dns_zone_ids = [azurerm_private_dns_zone.app_service.id]
  }
}
`;
}

/**
 * Generate ACR pull + Key Vault role assignments for a web app
 */
function generateRoleAssignments(prefix: string, resourceRef: string): string {
  return `
resource "azurerm_role_assignment" "${prefix}_acr_pull" {
  scope                            = azurerm_container_registry.main.id
  role_definition_name             = "AcrPull"
  principal_id                     = ${resourceRef}.identity[0].principal_id
  skip_service_principal_aad_check = true
}

resource "azurerm_role_assignment" "${prefix}_keyvault" {
  scope                            = data.azurerm_key_vault.main.id
  role_definition_name             = "Key Vault Secrets User"
  principal_id                     = ${resourceRef}.identity[0].principal_id
  skip_service_principal_aad_check = true
}`;
}
