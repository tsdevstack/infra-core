/**
 * Generate app-service-autoscale.tf: CPU autoscale for the App Service plans
 *
 * One azurerm_monitor_autoscale_setting per plan with `autoscaleMax` set
 * (Standard and Premium SKUs; Basic plans cannot autoscale). Mirrors the AWS
 * target of 70% CPU: one instance more when the plan's average CPU stays
 * above the scale-out line for 5 minutes, one less when it stays below the
 * scale-in line for 10 minutes, between the plan's instances and
 * autoscaleMax. Returns '' when no plan autoscales, so no file is written.
 */

import type {
  AzureInfraConfig,
  AppServicePlanScaling,
} from '../../types/config.ts';
import { AZURE_APP_SERVICE_AUTOSCALE } from '../../constants/azure-app-service.ts';

export function generateAppServiceAutoscaleTf(
  config: AzureInfraConfig,
): string {
  const plans: Array<{ id: string; scaling: AppServicePlanScaling }> = [
    { id: 'kong', scaling: config.kongScaling },
  ];
  if (Object.keys(config.frontends).length > 0) {
    plans.push({ id: 'nextjs', scaling: config.nextjsScaling });
  }

  const settings = plans
    .filter((plan) => plan.scaling.autoscaleMax !== null)
    .map((plan) =>
      generateAutoscaleSetting(
        plan.id,
        plan.scaling.instances,
        plan.scaling.autoscaleMax as number,
      ),
    );

  if (settings.length === 0) return '';

  return `# App Service autoscale (Kong + Next.js plans)
# Generated by: npx tsdevstack infra:generate
#
# CPU autoscale between minInstances and maxInstances. Only plans on a
# Standard or Premium SKU have a setting here: Basic plans cannot autoscale.
${settings.join('\n')}`;
}

/**
 * Generate one autoscale setting for a plan
 */
function generateAutoscaleSetting(
  planId: string,
  minimum: number,
  maximum: number,
): string {
  const a = AZURE_APP_SERVICE_AUTOSCALE;
  return `
resource "azurerm_monitor_autoscale_setting" "${planId}" {
  name                = "\${var.project_name}-\${var.environment}-${planId}-autoscale"
  location            = data.azurerm_resource_group.main.location
  resource_group_name = data.azurerm_resource_group.main.name
  target_resource_id  = azurerm_service_plan.${planId}.id
  tags                = local.tags

  profile {
    name = "cpu"

    capacity {
      minimum = ${minimum}
      maximum = ${maximum}
      default = ${minimum}
    }

    rule {
      metric_trigger {
        metric_name        = "${a.metricName}"
        metric_resource_id = azurerm_service_plan.${planId}.id
        time_grain         = "${a.timeGrain}"
        statistic          = "Average"
        time_window        = "${a.scaleOutWindow}"
        time_aggregation   = "Average"
        operator           = "GreaterThan"
        threshold          = ${a.scaleOutCpuPercent}
      }

      scale_action {
        direction = "Increase"
        type      = "ChangeCount"
        value     = "1"
        cooldown  = "${a.scaleOutCooldown}"
      }
    }

    rule {
      metric_trigger {
        metric_name        = "${a.metricName}"
        metric_resource_id = azurerm_service_plan.${planId}.id
        time_grain         = "${a.timeGrain}"
        statistic          = "Average"
        time_window        = "${a.scaleInWindow}"
        time_aggregation   = "Average"
        operator           = "LessThan"
        threshold          = ${a.scaleInCpuPercent}
      }

      scale_action {
        direction = "Decrease"
        type      = "ChangeCount"
        value     = "1"
        cooldown  = "${a.scaleInCooldown}"
      }
    }
  }
}
`;
}
